"""Generate the low-level Mojo API from the checksum-pinned raylib 6.2 header."""

import argparse
from dataclasses import dataclass
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / '.pixi/raylib/include/raylib.h'
EXISTING = {
    'Color', 'Vector2', 'Vector3', 'Camera3D', 'Matrix', 'Rectangle',
    'FilePathList', 'BoundingBox', 'Image', 'Texture', 'Font', 'Shader',
    'MaterialMap', 'Material', 'Mesh', 'ModelSkeleton', 'Model',
}
SCALARS = {
    'void': 'NoneType', 'bool': 'Bool', 'char': 'c_char',
    'unsigned char': 'UInt8', 'unsigned short': 'UInt16',
    'int': 'c_int', 'unsigned int': 'c_uint', 'long': 'c_long',
    'float': 'Float32', 'double': 'Float64',
}
RESERVED = {'type', 'from', 'in', 'out', 'var', 'ref', 'mut', 'self', 'alias', 'None'}
BANNER = '# Generated by scripts/generate_bindings.py; do not edit.\n'
CONSTANT_GROUPS = ('FLAG', 'LOG', 'KEY')


def snake(name):
    name = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', name)
    name = re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', name).lower()
    return name + '_' if name in RESERVED else name


def normalize(ctype):
    return re.sub(r'\s+', ' ', ctype.replace('*', ' * ')).strip()


@dataclass
class Field:
    ctype: str
    name: str
    count: int = 0


@dataclass
class Function:
    result: str
    name: str
    args: list
    variadic: bool
    doc: str


class Header:
    def __init__(self, text):
        if '#define RAYLIB_VERSION  "6.2"' not in text:
            raise ValueError('Expected the pinned raylib 6.2 header')
        self.text = text
        clean = re.sub(r'/\*.*?\*/|//[^\n]*', '', text, flags=re.S)
        self.structs = {}
        for name, body in re.findall(r'typedef struct (\w+)\s*\{(.*?)\}\s*\w+;', clean, re.S):
            fields = []
            for declaration in body.split(';'):
                if not declaration.strip():
                    continue
                first, *remaining = declaration.strip().split(',')
                field = self.declarator(first)
                fields.append(field)
                for extra in remaining:
                    fields.append(self.declarator(field.ctype + ' ' + extra.strip()))
            self.structs[name] = fields
        self.aliases = {}
        for ctype, name in re.findall(r'^typedef ([\w ]+?\s*\*?)\s*\b(\w+)\s*;', clean, re.M):
            if not ctype.startswith('struct '):
                self.aliases[name] = normalize(ctype)
        self.callbacks = re.findall(r'typedef .*?\(\*(\w+)\)\(.*?\);', clean)
        self.enums = {}
        self.constants = {}
        for body, name in re.findall(r'typedef enum\s*\{(.*?)\}\s*(\w+);', clean, re.S):
            if name == 'bool':
                continue
            self.enums[name] = []
            value = -1
            for item in body.split(','):
                if not item.strip():
                    continue
                key, *explicit = item.strip().split('=', 1)
                key = key.strip()
                value = int(eval(explicit[0], {'__builtins__': {}}, self.constants)) if explicit else value + 1
                self.constants[key] = value
                self.enums[name].append(key)
        self.colors = {}
        for name, rgba in re.findall(r'^#define (\w+)\s+CLITERAL\(Color\)\{([^}]+)\}', text, re.M):
            self.colors[name] = tuple(int(x.strip()) for x in rgba.split(','))
        for name, target in re.findall(r'^#define (\w+)\s+([A-Z][A-Z0-9_]+)\s*$', clean, re.M):
            if target in self.constants:
                self.constants[name] = self.constants[target]
        self.functions = []
        for line in text.splitlines():
            if not line.startswith('RLAPI '):
                continue
            match = re.match(r'RLAPI\s+(.*?)\b(\w+)\((.*?)\);\s*(?://\s*(.*))?$', line)
            if not match:
                raise ValueError(f'Unparsed function: {line}')
            result, name, args, doc = match.groups()
            variadic = '...' in args
            fields = [self.declarator(x) for x in args.split(',') if x.strip() not in ('void', '...', '')]
            self.functions.append(Function(normalize(result), name, fields, variadic, doc or name))
        if len(self.functions) != len(re.findall(r'^RLAPI ', text, re.M)):
            raise ValueError('Incomplete API parse')
        # Fail on unknown C types rather than silently generating a wrong ABI.
        for fields in self.structs.values():
            for field in fields:
                self.mojo_type(field.ctype)
        for function in self.functions:
            self.mojo_type(function.result)
            for field in function.args:
                self.mojo_type(field.ctype)

    @staticmethod
    def declarator(declaration):
        match = re.fullmatch(r'\s*(.*?)\b(\w+)\s*(?:\[(\d+)\])?\s*', declaration)
        if not match:
            raise ValueError(f'Unparsed declaration: {declaration}')
        ctype, name, count = match.groups()
        return Field(normalize(ctype), name, int(count or 0))

    def mojo_type(self, ctype):
        ctype = normalize(ctype)
        if '*' in ctype or ctype in self.callbacks:
            return 'UInt'
        if ctype in SCALARS:
            return SCALARS[ctype]
        if ctype in self.aliases:
            return self.mojo_type(self.aliases[ctype])
        if ctype in self.enums:
            return 'c_int'
        if ctype in self.structs:
            return ctype
        raise ValueError(f'Unknown C type: {ctype}')

    def field_type(self, field):
        scalar = self.mojo_type(field.ctype)
        return 'Tuple[' + ', '.join([scalar] * field.count) + ']' if field.count else scalar

    def field_name(self, struct, name):
        return {('Font', 'recs'): 'rectangles', ('BoundingBox', 'min'): 'minimum',
                ('BoundingBox', 'max'): 'maximum'}.get((struct, name), snake(name))

    def leaves(self, struct, mojo_prefix='', c_prefix=''):
        for field in self.structs[struct]:
            field_name = self.field_name(struct, field.name)
            for index in range(field.count or 1):
                m = mojo_prefix + (f'p{index}' if struct == 'Material' and field.name == 'params'
                                   else field_name + (f'[{index}]' if field.count else ''))
                c = c_prefix + field.name + (f'[{index}]' if field.count else '')
                scalar = self.mojo_type(field.ctype)
                if scalar in self.structs:
                    yield from self.leaves(scalar, m + '.', c + '.')
                else:
                    yield m, c, scalar


def render(header):
    abi = [BANNER, '"""Raylib C ABI types. Mesh/Model are linear; fixed arrays use tuples."""',
           'from std.ffi import c_char, c_int, c_uint',
           'from .types import ' + ', '.join(sorted(EXISTING)), '']
    for name, fields in header.structs.items():
        if name in EXISTING:
            continue
        abi += ['@fieldwise_init', f'struct {name}(ImplicitlyCopyable, RegisterPassable):']
        abi += [f'    var {header.field_name(name, f.name)}: {header.field_type(f)}' for f in fields]
        abi += ['', '']
    for name, ctype in header.aliases.items():
        abi += [f'comptime {name} = {header.mojo_type(ctype)}']
    for name in header.callbacks:
        abi += [f'comptime {name} = UInt']
    for name in header.enums:
        abi += [f'comptime {name} = c_int']

    constants = [BANNER, '"""raylib enum values, compatibility aliases, colors, and numeric macros."""',
                 'from .types import Color', '', 'comptime RAYLIB_VERSION_MAJOR = 6',
                 'comptime RAYLIB_VERSION_MINOR = 2', 'comptime RAYLIB_VERSION_PATCH = 0',
                 'comptime RAYLIB_VERSION = "6.2"', 'comptime PI = Float32(3.14159265358979323846)',
                 'comptime DEG2RAD = PI / 180', 'comptime RAD2DEG = 180 / PI', '']
    for group in CONSTANT_GROUPS:
        constants += [f'struct {group}:']
        constants += [f'    comptime {key.removeprefix(group + "_")} = {value}'
                      for key, value in header.constants.items() if key.startswith(group + '_')]
        constants += ['']
    for key, value in header.constants.items():
        group = key.split('_', 1)[0]
        expression = f'{group}.{key.removeprefix(group + "_")}' if group in CONSTANT_GROUPS else str(value)
        constants += [f'comptime {key} = {expression}']
    constants += [''] + [f'comptime {name} = Color({", ".join(map(str, rgba))})' for name, rgba in header.colors.items()]

    raw = [BANNER, '"""Complete raylib.h API. Pointers/callbacks are UInt addresses; zero is NULL.',
           '', 'Methods preserve C names and native ownership. String overloads borrow UTF-8',
           'only for the call and copy const char* results into String. Never use raw',
           'Begin/End/Close calls to bypass a linear owner.',
           '"""', 'from std.ffi import OwnedDLHandle, c_char, c_int, c_uint, c_long, external_call',
           'from .window import _copy_c_string',
           'from .abi import ' + ', '.join(header.structs), '',
           'def _format[*Args: RegisterPassable](text: UInt, *args: *Args) raises -> List[UInt8]:',
           '    # Format through a real C variadic call before dynamic pointer-only dispatch.',
           '    var probe = List[UInt8](length=1, fill=0)',
           '    var length = external_call["snprintf", c_int, num_fixed_args=3](',
           '        probe.unsafe_ptr(), UInt(0), text, args.get_loaded_kgen_pack()', '    )',
           '    if length < 0:', '        raise Error("invalid C format string")',
           '    var buffer = List[UInt8](length=Int(length) + 1, fill=0)',
           '    _ = external_call["snprintf", c_int, num_fixed_args=3](',
           '        buffer.unsafe_ptr(), UInt(len(buffer)), text, args.get_loaded_kgen_pack()', '    )',
           '    return buffer^', '', '', 'struct Raylib:',
           '    """Own the native library handle; native resources are managed explicitly."""',
           '    var handle: OwnedDLHandle', '',
           '    def __init__(out self, path: String) raises:', '        self.handle = OwnedDLHandle(path)', '']
    for f in header.functions:
        # These C calls consume native ownership, even though C passes structs
        # by value. Use the same linear types as the higher-level API.
        if f.name in ('UnloadMesh', 'UnloadModel'):
            resource = 'mesh' if f.name == 'UnloadMesh' else 'model'
            raw += [f'    def {f.name}(self, var {resource}: {resource.title()}):',
                    f'        """{f.doc}"""',
                    f'        {resource}^.unload(self.handle)', '']
            continue
        if f.name == 'LoadModelFromMesh':
            raw += ['    def LoadModelFromMesh(self, var mesh: Mesh) raises -> Model:',
                    f'        """{f.doc}"""',
                    '        return mesh^.into_model(self.handle)', '']
            continue
        arg_names = [snake(a.name) for a in f.args]
        strings = [i for i, a in enumerate(f.args) if a.ctype == 'const char *']
        result = header.mojo_type(f.result)
        for string_overload in ([False, True] if strings else [False]):
            args = [f'{"var " if string_overload and i in strings else ""}{name}: '
                    + ('String' if string_overload and i in strings else header.mojo_type(a.ctype))
                    for i, (a, name) in enumerate(zip(f.args, arg_names))]
            signature = f'    def {f.name}' + ('[*Args: RegisterPassable]' if f.variadic else '')
            signature += '(self' + (', ' + ', '.join(args) if args else '')
            signature += ', *args: *Args' if f.variadic else ''
            copy_string = string_overload and f.result == 'const char *'
            public_result = 'String' if copy_string else result
            signature += ') raises' + (f' -> {public_result}' if result != 'NoneType' else '') + ':'
            raw += [signature, f'        """{f.doc.replace(chr(34), chr(39))}"""']
            values = [f'UInt(Int({name}.as_c_string_span().ptr()))' if string_overload and i in strings else name
                      for i, name in enumerate(arg_names)]
            ret = 'return ' if result != 'NoneType' else ''
            if string_overload:
                call = f'self.{f.name}(' + ', '.join(values + (['*args'] if f.variadic else [])) + ')'
                raw += [f'        {ret}' + ('_copy_c_string(' + call + ')' if copy_string else call)]
            elif f.variadic:
                raw += [f'        var buffer = _format({arg_names[-1]}, *args)',
                        '        var format_string = String("%s")',
                        f'        {ret}self.handle.get_function[{result}]("{f.name}")('
                        + ', '.join(arg_names[:-1] + ['format_string.as_c_string_span()', 'buffer.unsafe_ptr()']) + ')']
            else:
                raw += [f'        {ret}self.handle.get_function[{result}]("{f.name}")(' + ', '.join(values) + ')']
            raw += ['']

    types = list(header.structs) + list(header.aliases) + header.callbacks + list(header.enums)
    # Texture2D at the package root remains the existing owning wrapper.
    types = [t for t in types if t != 'Texture2D']
    exports = [BANNER, '"""raylib 6.2 bindings with linear Window and Frame owners."""',
               'from .abi import ' + ', '.join(types),
               'from .constants import ' + ', '.join(
                   ['RAYLIB_VERSION', 'RAYLIB_VERSION_MAJOR', 'RAYLIB_VERSION_MINOR', 'RAYLIB_VERSION_PATCH', 'PI', 'DEG2RAD', 'RAD2DEG']
                   + list(CONSTANT_GROUPS)
                   + list(header.constants) + list(header.colors)),
               'from .raw import Raylib',
               'from .window import Window, Frame, ScissorFrame, Scene3D, Scissor3D',
               'from .resources import TextFont, Texture2D', 'from .library import Library']
    license_text = header.text[header.text.index('/*'):header.text.index('*/') + 2]
    return {'abi.mojo': '\n'.join(abi) + '\n', 'constants.mojo': '\n'.join(constants) + '\n',
            'raw.mojo': '\n'.join(raw) + '\n', '__init__.mojo': '\n'.join(exports) + '\n',
            'LICENSE.raylib': license_text + '\n'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--header', type=Path, default=HEADER)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    header = Header(args.header.read_text())
    compiler = shutil.which('mojo') or str(ROOT / '.pixi/envs/default/bin/mojo')
    with tempfile.TemporaryDirectory(prefix='raylib generate ') as tmp:
        directory = Path(tmp)
        outputs = render(header)
        for name, content in outputs.items():
            (directory / name).write_text(content)
        for source in directory.glob('*.mojo'):
            result = subprocess.run([compiler, 'format', str(source)],
                                    capture_output=True, text=True)
            if result.returncode:
                raise SystemExit(result.stdout + result.stderr)
        for name in outputs:
            content = (directory / name).read_text()
            target = ROOT / 'raylib' / name
            if args.check:
                if not target.exists() or target.read_text() != content:
                    raise SystemExit(f'{target.relative_to(ROOT)} needs regeneration')
            else:
                target.write_text(content)
    print(f'{"Checked" if args.check else "Generated"} {len(header.functions)} functions, '
          f'{len(header.structs)} structs, {len(header.constants)} enum constants, {len(header.colors)} colors')


if __name__ == '__main__':
    main()
